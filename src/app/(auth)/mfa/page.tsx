'use client';

import * as React from 'react';
import { useRouter } from 'next/navigation';
import Link from 'next/link';
import { ShieldCheck, KeyRound, ArrowRight } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Card, CardContent, CardDescription, CardFooter, CardHeader, CardTitle } from '@/components/ui/card';

export default function MfaVerificationPage() {
  const router = useRouter();
  const [code, setCode] = React.useState('');
  const [error, setError] = React.useState<string | null>(null);
  const [isVerifying, setIsVerifying] = React.useState(false);

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (code.trim().length !== 6) {
      setError('Please enter a valid 6-digit numeric verification code.');
      return;
    }
    setIsVerifying(true);
    setTimeout(() => {
      setIsVerifying(false);
      router.push('/');
    }, 600);
  };

  return (
    <div className="flex min-h-screen w-full items-center justify-center bg-zinc-50 p-4 dark:bg-zinc-950">
      <div className="w-full max-w-md space-y-6">
        <div className="flex flex-col items-center space-y-2 text-center">
          <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-zinc-900 text-white shadow-md dark:bg-zinc-100 dark:text-zinc-900">
            <KeyRound className="h-5 w-5" />
          </div>
          <h1 className="text-xl font-bold tracking-tight text-zinc-900 dark:text-zinc-50">
            Two-Factor Verification
          </h1>
          <p className="text-xs text-zinc-500 dark:text-zinc-400">
            Enter the 6-digit code generated by your authenticator app.
          </p>
        </div>

        <Card className="shadow-lg border-zinc-200 dark:border-zinc-800">
          <CardHeader className="space-y-1 pb-4">
            <CardTitle className="text-base font-semibold">Security Challenge</CardTitle>
            <CardDescription className="text-xs">
              MFA is strictly required for this corporate account.
            </CardDescription>
          </CardHeader>
          <form onSubmit={handleSubmit}>
            <CardContent className="space-y-4">
              <div className="space-y-1.5 flex flex-col items-center">
                <Label htmlFor="mfa-code" className="text-xs self-start">Authenticator Code</Label>
                <Input
                  id="mfa-code"
                  type="text"
                  maxLength={6}
                  placeholder="000 000"
                  value={code}
                  onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
                  className="text-center font-mono text-lg tracking-widest h-11 w-48"
                  autoFocus
                  required
                />
              </div>

              {error && <p className="text-xs text-red-600 text-center font-medium">{error}</p>}

              <Button type="submit" className="w-full text-xs" disabled={isVerifying}>
                {isVerifying ? 'Verifying Code...' : 'Verify & Continue'}
              </Button>
            </CardContent>
          </form>

          <CardFooter className="justify-center border-t border-zinc-100 p-3 dark:border-zinc-800">
            <Link href="/login" className="text-xs text-zinc-500 hover:text-zinc-900 dark:hover:text-zinc-100">
              Return to Sign In
            </Link>
          </CardFooter>
        </Card>
      </div>
    </div>
  );
}
